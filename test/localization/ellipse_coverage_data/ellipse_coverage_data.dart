/// **The two committed data files the guide's ellipse figures are drawn from**
/// — task 11.336. Chi-square only: the scale the app uses. (11.334's F
/// columns stay in `ellipse_coverage_simulation_test.dart`'s printout as a
/// labeled record and are deliberately not here.)
///
/// - `coverage_chi_square.csv` — how often the app's 95% ellipse contained the
///   animal, per number of bearings and bearing spread, and the same with the
///   true κ as the reference.
/// - `worked_examples.json` — six single fixes, each with everything the
///   explanatory figures need *from the app itself*: the stations, the
///   bearings, the solver's path, κ and where it came from, the covariance,
///   and the 1-SD and 95% ellipses.
///
/// **Regenerated by one command, and a test fails when a committed file
/// differs** (`ellipse_coverage_data_test.dart`; the command is in
/// `README.md` beside the files). Every number is rounded to 6 decimals when
/// written, so another machine's last-bit differences in sine and cosine
/// cannot show up as a diff.

/// The examples: how many bearings, the bearing spread, and which outcome the
/// example shows. **Chosen once and stated, not searched for the prettiest
/// picture:** each takes the first fix, in its own random stream, with that
/// outcome. A miss is shown at three bearings, where it is the usual result
/// (coverage 40–43%); the rest show a fix whose ellipse contains the animal,
/// the usual result from five bearings up (68–86%). The guide must say which
/// is usual — the cell's own coverage is written into each example.
const workedExampleSpecs = <({int bearings, double spreadDeg, bool covered})>[
  (bearings: 3, spreadDeg: 5.0, covered: false),
  (bearings: 3, spreadDeg: 15.0, covered: false),
  (bearings: 5, spreadDeg: 5.0, covered: true),
  (bearings: 5, spreadDeg: 15.0, covered: true),
  (bearings: 10, spreadDeg: 5.0, covered: true),
  (bearings: 10, spreadDeg: 15.0, covered: true),
];

/// Seed for example *k* is this plus *k*.
const workedExampleSeed = 11336;

/// The chi-square table as CSV.
String buildCoverageCsv() {
  final cells = coverageCells();
  final lines = <String>[
    'bearings,spread_sd_deg,runs,fixes_with_ellipse,no_ellipse,'
        'covered_chi_square,coverage_chi_square,'
        'covered_chi_square_true_kappa,coverage_chi_square_true_kappa',
  ];
  for (final n in simulationCounts) {
    for (final sd in simulationSpreadsDeg) {
      final c = cells[(n, sd)]!;
      lines.add([
        n,
        sd.toStringAsFixed(0),
        c.runs,
        c.used,
        c.noEllipse,
        c.chiCovered,
        c.chi.toStringAsFixed(4),
        c.trueKappaCovered,
        c.trueKappa.toStringAsFixed(4),
      ].join(','));
    }
  }
  return '${lines.join('\n')}\n';
}

/// The six worked examples as JSON.
String buildWorkedExamplesJson() {
  final cells = coverageCells();
  final examples = [
    for (var k = 0; k < workedExampleSpecs.length; k++)
      _workedExample(k, workedExampleSpecs[k], cells),
  ];
  final document = <String, Object?>{
    'about': 'Six single fixes from the simulation behind task 11.323, '
        'solved by the app\'s own solver (LenthSolver, the meters '
        'configuration). Written by task 11.336; see README.md for every '
        'field and the one command that regenerates this file.',
    'examples': examples,
  };
  return '${const JsonEncoder.withIndent('  ').convert(document)}\n';
}

Map<String, Object?> _workedExample(
  int index,
  ({int bearings, double spreadDeg, bool covered}) spec,
  Map<(int, double), CoverageCell> cells,
) {
  final random = math.Random(workedExampleSeed + index);
  final kappaTrue = kappaForCircularSd(spec.spreadDeg);

  for (var attempt = 0; attempt < 100000; attempt++) {
    final stations = drawStations(random, spec.bearings, kappaTrue);
    final trace = LenthTrace();
    final result = LenthSolver.solve(
      observationsFor(stations),
      config: appConfig,
      trace: trace,
    );
    final cov = result.covariance;
    final ellipse = result.ellipse;
    if (!result.hasEstimate || cov == null || ellipse == null) continue;

    final d2 = mahalanobisSquared(-result.x!, -result.y!, cov);
    final covered = d2 <= chiSquare95;
    if (covered != spec.covered) continue;

    final cell = cells[(spec.bearings, spec.spreadDeg)]!;
    return _describe(
      index: index,
      spec: spec,
      fixesBeforeThis: attempt,
      cellCoverage: cell.chi,
      cellCoverageTrueKappa: cell.trueKappa,
      kappaTrue: kappaTrue,
      stations: stations,
      result: result,
      trace: trace,
      cov: cov,
      ellipse95: ellipse,
      d2: d2,
      covered: covered,
    );
  }
  throw StateError(
    'worked example $index (${spec.bearings} bearings, ${spec.spreadDeg}°, '
    'covered=${spec.covered}) found no matching fix in 100,000 draws',
  );
}

Map<String, Object?> _describe({
  required int index,
  required ({int bearings, double spreadDeg, bool covered}) spec,
  required int fixesBeforeThis,
  required double cellCoverage,
  required double cellCoverageTrueKappa,
  required double kappaTrue,
  required List<SimulatedStation> stations,
  required LocalizationResult result,
  required LenthTrace trace,
  required EstimateCovariance cov,
  required UncertaintyEllipse ellipse95,
  required double d2,
  required bool covered,
}) {
  // The 1-SD ellipse: the points whose Mahalanobis distance squared is 1.
  // The same eigen-decomposition the solver does for the 95% one, with the
  // scale 1 in place of 5.991 — and **checked against the solver's own 95%
  // ellipse below**, so the copy cannot drift from the app unnoticed.
  final half = (cov.xx + cov.yy) / 2.0;
  final diff = math.sqrt(
    ((cov.xx - cov.yy) / 2.0) * ((cov.xx - cov.yy) / 2.0) + cov.xy * cov.xy,
  );
  final lambda1 = half + diff;
  final lambda2 = math.max(half - diff, 0.0);
  final oneSdMajor = math.sqrt(lambda1);
  final oneSdMinor = math.sqrt(lambda2);
  final rotationDeg =
      Angles.radToDeg(0.5 * math.atan2(2 * cov.xy, cov.xx - cov.yy));
  final scale = math.sqrt(chiSquare95);
  _agree(oneSdMajor * scale, ellipse95.semiMajorAxis, 'major axis');
  _agree(oneSdMinor * scale, ellipse95.semiMinorAxis, 'minor axis');
  _agree(rotationDeg, ellipse95.rotationDegrees, 'rotation');

  Map<String, Object?> ellipseJson(double major, double minor, double k) => {
        'scale_k': _r(k),
        'semi_major_m': _r(major),
        'semi_minor_m': _r(minor),
        'major_axis_rotation_ccw_from_east_deg': _r(rotationDeg),
        'major_axis_compass_bearing_deg':
            _r(Angles.normalizeDegrees(90.0 - rotationDeg)),
      };

  Map<String, double> point(double x, double y) => {'x_m': _r(x), 'y_m': _r(y)};

  return {
    'id': 'n${spec.bearings}_sd${spec.spreadDeg.toStringAsFixed(0)}',
    'bearings': spec.bearings,
    'bearing_spread_sd_deg': spec.spreadDeg,
    'true_kappa': _r(kappaTrue),
    'seed': workedExampleSeed + index,
    'fixes_drawn_before_this_one': fixesBeforeThis,
    'shows': covered ? 'ellipse contains the animal' : 'ellipse misses the animal',
    'this_cells_coverage_chi_square': _r(cellCoverage, 4),
    'this_cells_coverage_true_kappa': _r(cellCoverageTrueKappa, 4),
    'plane': 'meters; x east, y north; the animal is at the origin',
    'true_point': point(0, 0),
    'stations': [
      for (var i = 0; i < stations.length; i++)
        () {
          final s = stations[i];
          final reading = s.trueThetaRad + s.errorRad;
          final trueCompass = Angles.mathRadiansToCompassDegrees(s.trueThetaRad);
          final readCompass = Angles.mathRadiansToCompassDegrees(reading);
          return {
            'number': i + 1,
            ...point(s.x, s.y),
            'theta_math_rad': _r(reading),
            'true_bearing_compass_deg': _r(trueCompass),
            'bearing_compass_deg': _r(readCompass),
            'bearing_error_compass_deg': _r(
              _signedDegrees(readCompass - trueCompass),
            ),
            'leftover_angle_deg': _r(
              // Compass sense: positive = the reading points clockwise of the
              // line from the station to the estimate.
              -Angles.radToDeg(trace.leftoverAnglesRad[i]),
            ),
            'leftover_angle_math_rad': _r(trace.leftoverAnglesRad[i]),
          };
        }(),
    ],
    'estimate': {
      ...point(result.x!, result.y!),
      'distance_from_true_point_m':
          _r(math.sqrt(result.x! * result.x! + result.y! * result.y!)),
      'iterations': result.iterations,
      'warnings': [for (final w in result.warnings) w.name],
    },
    'solver_path': {
      'note': 'Each step is Lenth\'s Eq. 2.6 applied at the current point. '
          '`shortened` marks a step that was cut back because the whole step '
          'made the fit worse; `fraction` is how much of it was taken. '
          '`sum_cosine` is Σ cos(θᵢ − μᵢ), the fit being maximized.',
      'start': {
        ...point(trace.startX!, trace.startY!),
        'sum_cosine': _r(trace.startSumCosine!),
      },
      'steps': [
        for (final st in trace.steps)
          {
            'number': st.number,
            'from': point(st.fromX, st.fromY),
            'full_step_to': point(st.fullStepX, st.fullStepY),
            'fraction': _r(st.fraction),
            'shortened': st.shortened,
            'to': point(st.toX, st.toY),
            'sum_cosine': _r(st.sumCosine),
            'converged': st.converged,
            'rejected': st.rejected,
          },
      ],
      'shortened_steps': [
        for (final st in trace.steps)
          if (st.shortened) st.number,
      ],
    },
    'kappa': {
      'value': _r(result.kappa!),
      'mean_cosine': _r(trace.meanCosine!),
      'mean_resultant_length': _r(result.meanResultantLength!),
      'note': 'kappa is the inverse of the von Mises mean-resultant function '
          'applied to mean_cosine, the average of cos(leftover angle) over '
          'the bearings. The leftover angles are on each station above.',
    },
    'covariance_m2': {
      'xx': _r(cov.xx),
      'yy': _r(cov.yy),
      'xy': _r(cov.xy),
      'standard_error_x_m': _r(cov.seX),
      'standard_error_y_m': _r(cov.seY),
      'correlation': _r(cov.correlation),
    },
    'ellipses': {
      'one_sd': ellipseJson(oneSdMajor, oneSdMinor, 1.0),
      'ninety_five': ellipseJson(
        ellipse95.semiMajorAxis,
        ellipse95.semiMinorAxis,
        chiSquare95,
      ),
    },
    'true_point_mahalanobis_squared': _r(d2),
    'covered_by_95_ellipse': covered,
  };
}

void _agree(double mine, double apps, String what) {
  if ((mine - apps).abs() > 1e-9 * math.max(1.0, apps.abs())) {
    throw StateError(
      'the 1-SD ellipse copy disagrees with the solver\'s 95% ellipse on '
      '$what: $mine against $apps — the generator has drifted from the app',
    );
  }
}

double _signedDegrees(double d) {
  var v = d % 360.0;
  if (v > 180.0) v -= 360.0;
  if (v <= -180.0) v += 360.0;
  return v;
}

/// Rounded to [places] decimals, with no negative zero.
double _r(double v, [int places = 6]) {
  final rounded = double.parse(v.toStringAsFixed(places));
  return rounded == 0 ? 0.0 : rounded;
}
